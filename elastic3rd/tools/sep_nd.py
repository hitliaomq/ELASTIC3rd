def getAverage(EC):
    EC_ave = {}
    for key in EC:
        EC_ave[key] = float(np.mean(EC[key]))
    return EC_ave

def simplifyEC(EC, CrystalType = "C1", Ord = 3):
    #EC is dict, e.g. EC = {111: [-1234, -2345], 112: [-2222, -333]}
    CoefInd = symdata.coef_ind(CrystalType, Ord)
    EC_smp = {}
    for key in EC:
        Num = essym.cijk2num(key, Ord)[0]
        #print(Num)
        if CoefInd[int(Num)] != 0:
            #delete current item
            NewNum = CoefInd[Num]
            NewCIJ = int(essym.num2cijk(NewNum, Ord))
            ECi = {NewCIJ : EC[key]}
            EC_smp = mergDict(EC_smp, ECi)
    return EC_smp

def simplifyEC_Ind(EC_Ind, CrystalType = "C1", Ord = 3):
    #EC_Ind is a list, e.g. EC_Ind = [111, 112, 113, 114, 115, 116]
    #print("The original CIJ is:")
    EC_Ind_Uniq = symdata.get_unique(EC_Ind)
    Num = essym.cijk2num(EC_Ind_Uniq, Ord)
    CoefInd = symdata.coef_ind(CrystalType, Ord)
    EC_Ind_smp = np.empty(0, dtype=np.int8)
    for i in Num:
        if CoefInd[i] != 0:
            EC_Ind_smp = np.append(EC_Ind_smp, CoefInd[i])
    EC_Ind_smp = essym.num2cijk(EC_Ind_smp, Ord)
    #print(EC_Ind_smp)
    EC_Ind_smp = symdata.get_unique(EC_Ind_smp)
    #print("The simplified CIJ is :")
    #print(EC_Ind_smp)
    return EC_Ind_smp

def cal_ec_single(strainmode, StrainAmp, EC_Ind = np.empty(0, dtype=np.int8), BaseName = None, NP = 8, P0 = np.zeros(6), acc=2):
    #strainmode is the strain mode, it a dict, which can be generated by gen_strainmode_single(Ind, acc)
    #strain is the strain amplitude, the true strain is strain/100
    #P0 is the stress of initial structure
    #EC_Ind is the previously calculated EC
    #Note:
    #   This function support multi-strainmode, but it does not simplify multi-strainmode
    #   Using for single is recommended
    EC = {}
    #EC_Ind = np.empty(0, dtype=np.int8)
    if type(StrainAmp) is float or type(StrainAmp) is int :
        StrainAmp = np.array([StrainAmp])
    # do a loop for each key-strainmode(list) pair
    for key in strainmode:
        #Create the mode Folder, named using the key
        createAndEnter(str(key), BaseName)
        strainmodei = strainmode[key]  # This a 2D matrix
        #TO JUDGE IF THE CURRENT IS EXIST IN PREVIOUS LIST
        if key in EC_Ind:
            existWarning()
            os.chdir("../")
            continue
        # do a loop for each strain
        EC_strain = {}
        for i in range(0, len(StrainAmp)):
            # Create the strain folder, named as strain + value_of_strain
            straini = StrainAmp[i]/100.
            strainFolder = "Strain" + str(StrainAmp[i])
            pare_path = os.getcwd()
            createAndEnter(strainFolder, BaseName)
            #do a loop for each strainmode
            StressMat = np.zeros((len(strainmodei), 6))
            for j in range(0, len(strainmodei)):
                #Create the specific strain name
                strainmodeij = strainmodei[j]       #This is a verctor
                subFolder = "".join([str(int(k)) for k in strainmodeij])
                createAndEnter(subFolder, BaseName)
                fullpath = search_previous(pare_path, StrainAmp[i], strainmodeij)
                if os.path.exists(fullpath):
                    shutil.copyfile(fullpath, './Stress_Strain.txt')
                    E0 = np.loadtxt("Stress_Strain.txt") 
                    strainmodeMat = crydef.vec2matrix(strainmodeij)
                    (PK, PKvec) = symstr.cauchy2pk(E0, straini*strainmodeMat)
                else:
                    (PK, PKvec) = runFPgetE(straini, strainmodeij, BaseName, NP, flag_test)

                print("Lagrangian stress:")
                print(PKvec) 
                StressMat[j,:] = PKvec
                os.chdir("../")
            #Calculate the corresponding Elastic Constants
            P0 = 0.
            (ECi, EC_Indi) = calEqs(key, StressMat, straini, P0, acc)
            ##For different strainAmp, the EC_Ind is redundent, do not need append
            #EC_Ind = np.append(EC_Ind, EC_Indi)
            #For ECi, it need be append to the corresponding list
            EC_strain = mergDict(EC_strain, ECi)
            writejson(ECi, filename = "EC-Modei.json")
            os.chdir("../")
        writetxt(EC_strain, filename = "EC-Strain.txt")
        EC_Ind = np.append(EC_Ind, EC_Indi)
        EC = mergDict(EC, EC_strain)
        os.chdir("../")
    #print(EC_Ind)
    #print(EC)
    return (EC, EC_Ind)

def search_previous(path, strainampi, strainmode):
    '''
    path: the parent path of different strain
    '''
    path = os.path.abspath(path)
    fullpath = 'notexist'
    strainmode_int = [int(k) for k in strainmode]
    if 1 in strainmode_int or -1 in strainmode_int:
        strainmode_str = [str(int(2*k)) for k in strainmode_int]
        fullpath = os.path.join(path, "Strain" + str(0.5*strainampi), ''.join(strainmode_str), 'Stress_Strain.txt')
    elif 2 in strainmode_int or -2 in strainmode_int:
        strainmode_str = [str(int(k/2)) for k in strainmode_int]
        fullpath = os.path.join(path, "Strain" + str(2.*strainampi), ''.join(strainmode_str), 'Stress_Strain.txt')
    else:
        pass
        #raise ValueError('Not support yet.')
    return fullpath


def update_poscar(strain, strainmodeMat, BaseName = None):
    BaseVec = eglue.get_base_vec(BaseName)
    strainmodeMat = strain*strainmodeMat
    BaseVecNew = BaseVec .dot (crydef.strain2deformgrad(strainmodeMat))
    crylat.print_lattice(BaseVecNew) 
    eglue.write_base_vec(BaseName, BaseVecNew)

def mergDict(EC, ECi):
    '''
    #Merge ECi into EC
    '''
    for key_single in ECi:
        if key_single in EC:
            EC[key_single].append(ECi[key_single][0])
        else:
            EC[key_single] = ECi[key_single]
    return EC

