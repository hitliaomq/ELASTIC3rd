def writetxt(EC, filename = "E3rd-ND.txt"):
    #Write dict to txt file, only for EC file
    #Input, EC is a dict, like{"111": -1092, "112": -584, ...}
    datafile = open(filename, "w+")
    head = []
    value = []
    for key in EC:
        head.append(str(int(key)))
        value.append(EC[key])
    datafile.write("    ".join(head) + "\n")
    valueT = list(list(i) for i in zip(*value))
    for i in range(0, len(valueT)):
        datafile.write("    ".join(str(i) for i in valueT[i]) + "\n")

def match_acc2(CIJ, strainmode, strainmode_acc2, endpoint=True):
    '''
    Get the index of acc2 result from acc4 result
    Parameters
    ----------
        CIJ: int
            the index of elastic constant, e.g. 111
        strainmode/strainmode_acc2: dict
            The strainmode dict of SEP-ND methods. It can be generated by gen_strainmode_all function.
            e.g. {111: [[], [], ...], 112: [[], [], ...]}
        endpoint: bool
            If endpoint is true, use the end point as the acc2's calculation.
    Returns
    -------
        index_acc2: the index of acc2
    '''
    strainmode = strainmode[CIJ]
    strainmode_acc2 = strainmode_acc2[CIJ]
    if endpoint:
        strainmode_acc2 = 2.*strainmode_acc2
    ind_acc2 = []
    for strain_acc2 in strainmode_acc2:
        for i, strain_acc4 in enumerate(strainmode):
            if (strain_acc2==strain_acc4).all():
                ind_acc2.append(i)
    return ind_acc2

