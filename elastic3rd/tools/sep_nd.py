def existWarning():
    print("Warning: This elastic constant is existed in previous strainmode!")

def getAllCIJ(Ind, ec = np.zeros(6)):
    '''
    #To generate of the output of single strain, if ec = 0, 
    #  then used to generate the all CIJ according to the Ind
    #Input: Ind, like [1, 2, 5]
            ec, the elastic constant, 1x6
    #Output: EC_CIJ, like [125, 225, 235, 245, 255, 256]
        EC, like {111:[1, 2, 3], 112:[2, 2, 2], ...}
    #Test:
        Ind = [1, 2, 5]
        (EC, EC_CIJ) = getAllCIJ(Ind)
        print(EC_CIJ)
    '''
    EC = {}
    EC_CIJ = np.empty(0, dtype=np.int8)
    for i in range(0, 6):
        keyi = Ind
        keyi[0] = int(i+1)
        keyi = np.sort(keyi)
        keyi = Ind2CIJ(keyi)
        EC[keyi] = [ec[i]]
        EC_CIJ = np.append(EC_CIJ, keyi)
    return (EC, EC_CIJ)

