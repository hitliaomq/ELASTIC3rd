def gen_input_by_mpid(mpid):
    """
    Run the elastic3rd according to the mpid(materials project)
    The input file is generated by pymatgen
    """
    from pymatgen.ext.matproj import MPRester
    from pymatgen.io.vasp.sets import MPRelaxSet
    from dfttk.input_sets import RelaxSet
    struct = MPRester().get_structure_by_material_id(mpid, conventional_unit_cell=True)
    formula = struct.composition.reduced_formula
    #struct.to(fmt="POSCAR", filename="POSCAR")
    #RelSet = MPRelaxSet(struct)
    RelSet = RelaxSet(struct)
    RelSet.CONFIG['KPOINTS'].update({'grid_density': 4000})
    RelSet.write_input(output_dir=".")
    #print(formula)

def gen_input_by_from_sg(a, ele, phase="bcc"):
    """
    Run the elastic3rd according to the spacegroup (note: only for bcc and fcc)
    The input file is generated by pymatgen
    """
    from dfttk.input_sets import RelaxSet
    from pymatgen.core.structure import Structure
    from pymatgen.core.lattice import Lattice
    spacegroup = {"bcc": "Im-3m",
          "fcc": "Fm-3m",
          "hcp": "194"}
    sg = spacegroup[phase]
    if phase == "bcc" or phase == "fcc":
        struct = Structure.from_spacegroup(sg, Lattice.cubic(a),
                                       [ele], [[0, 0, 0]])
    elif phase == "hcp":
        c = a[0]*a[1]
        a = a[0]
        b = a
        alpha = 90.
        beta = 90.
        gamma = 120.
        struct = Structure.from_spacegroup(sg, Lattice.from_parameters(a=a, b=b, c=c, alpha=alpha, beta=beta, gamma=gamma),
                                       [ele], [[1./3., 2./3., 0.25]])
    else:
        raise Exception("Current {phase} is not supported.".format(phase=phase))
    formula = struct.composition.reduced_formula
    #struct.to(fmt="POSCAR", filename="POSCAR")
    #RelSet = MPRelaxSet(struct)
    RelSet = RelaxSet(struct)
    RelSet.CONFIG['KPOINTS'].update({'grid_density': 4000})
    RelSet.write_input(output_dir=".")
    #print(formula)

def get_parameter_by_potcar(potcar="POTCAR"):
    """
    Get the ENMAX value from POTCAR
    Parameter
    ---------
        potcar: The name of the POTCAR
    Return
    ------
        ENMAX: the ENMAX value
    """
    with open(potcar, "r") as fid:
        ELE = []
        ENMAX = []
        for linei in fid:
            if "VRHFIN" in linei:
                ELE.append(linei.split("=")[1].split(":")[0].strip())
            if "ENMAX" in linei:
                ENMAX.append(float(linei.split(";")[0].split("=")[1]))
    return ELE, ENMAX

def modify_incar():
    #NOTE: This is only for pure elements for the is_metal
    #      For compounds, be careful
    incar_settings = {"ISIF": "2", "LCHARG": "FALSE", "LWAVE": "FALSE", "EDIFFG": "-1E-3",
                      "EDIFF": "1E-5", "LREAL": "Auto", "ISTART": "1", "MAGMOM": ""}
    if os.path.exists("POTCAR"):
        from pymatgen.core.periodic_table import Element
        ELE, ENMAX = get_parameter_by_potcar("POTCAR")
        if ELE[0] in ["Fe", "Co", "Ni", "Mn", "Ru", "Rh", "Pd", "Cd", "Ir", "La", "Ce", "Pr", "Nd", "Ac", "U", "Np", "Pu"]:
            incar_settings["ISPIN"] = "2"
        incar_settings["ENCUT"] = str(1.3 * max(ENMAX))
        IsMetal = True
        for elei in ELE:
            if not Element(elei).is_metal:
                IsMetal = False
        if IsMetal:
            incar_settings["ISMEAR"] = "0"
            incar_settings["SIGMA"] = "0.02"
        else:
            incar_settings["ISMEAR"] = "-5"
    esvasp.check_incar(Settings = incar_settings)

def write_INPUT():
    input_str = """BaseName        C
Continue        1
FlagSE          S
CalMode         W
CrystalType     c1
Ord             3
EnergyCode      VASP
EnergyRun       1
MaxStrain       6
STEPS           16
NP              24"""
    with open("INPUT.e3rd", "w+") as fid:
        fid.write(input_str)

def run_all_pure_ele_from_sg(phase="bcc", flag_run=True, startpoint='Li', endpoint='Pu'):
    from monty.serialization import loadfn
    ele_dict = loadfn(os.path.join(os.path.dirname(__file__), "PureEle.json"))
    a_name = "a_" + phase
    for ele in ele_dict:
        if Element(ele).Z < Element(startpoint).Z:
            continue
        if Element(ele).Z > Element(endpoint).Z:
            return None
        if phase == "bcc" or phase == "fcc":
            a = ele_dict[ele][a_name]
            crystaltype = "c1"
        elif phase == "hcp":
            crystaltype = "h1"
            try:
                a = ele_dict[ele][a_name]
            except Exception as e:
                a = ele_dict[ele]["a_bcc"]
                a = [a / (2. ** (1./6.)), (8./3.) ** (1./2.)]
        else:
            raise Exception("Current {phase} is not supported.".format(phase=phase))
        folder_name = phase + "-" + ele
        if not os.path.exists(folder_name):
            os.mkdir(folder_name)
        shutil.copyfile("runElastic3rd.py", folder_name + "/" + "runElastic3rd.py")
        os.chdir(folder_name)
        if not os.path.exists("INPUT.e3rd"):
            gen_input_by_from_sg(a, ele, phase=phase)
            modify_incar()
            write_INPUT()
            comtools.check_input(input_sets = {"BaseName": ele, "CrystalType": crystaltype})
        if flag_run:
            os.system("python runElastic3rd.py")
        os.chdir("..")

