def indpen2dict(indpenC, CIJ_index=[11, 12, 44]):
    '''
    Convert the independent CIJ to standard dict, e.g. {11: C11, 12: C12, 44: C44}
    Parameters
    ----------
        indpenC: list/dict
            Independent elastic constants
                If list, in the order of uniq. e.g. [1054, 119, 562] for c1 and Ord=2 means C11=1054, C12=119,C44=563 
                If dict, the index of indpendent ec is the key
                    The key can be int or float or str (starts with C or just numbers), such as 11, '11', '11.0', 'C11' 
        CIJ_index: list
            The index of indepenC, can be generated by essym.num2cijk
    Return
    ------
        indpenC_new: dict
            The standard dict for independent CIJ, e.g. {11: C11, 12: C12, 44: C44}
    '''
    if len(CIJ_index) != len(indpenC):
        raise ValueError('The length of provided independent CIJ indpenC(len={}) did not match the Ord (len={})'.format(len(indpenC), len(CIJ_index)))
    if isinstance(indpenC, (list, tuple, np.ndarray)):
        indpenC_new = dict(zip(CIJ_index, indpenC))
    elif isinstance(indpenC, dict):
        CIJ_key = list(indpenC.keys())
        indpenC_new = {}
        for i, CIJ_keyi in enumerate(CIJ_key):
            if isinstance(CIJ_keyi, (str)) and CIJ_keyi.lower().startswith('c'):
                indpenC_new[int(CIJ_keyi[1:])] = indpenC[CIJ_keyi]
                CIJ_key[i] = int(CIJ_keyi[1:])
            else:
                indpenC_new[int(CIJ_keyi)] = indpenC[CIJ_keyi]
                CIJ_key[i] = int(CIJ_keyi)
        for CIJ_index_i in CIJ_index:
            if CIJ_index_i not in CIJ_key:
                raise ValueError('The key in the indpenC is not match with crystal type.')
    else:
        raise ValueError('Not supported type of indpenC.')
    return indpenC_new

def indpen2full(indpenC, Ord=2, CrystalType='c1'):
    '''
    Covert the independent elastic constants to full (in Voigt)

    Parameters
    ----------
        indpenC: list/dict
            Independent elastic constants
                If list, in the order of uniq. e.g. [1054, 119, 562] for c1 and Ord=2 means C11=1054, C12=119,C44=563 
                If dict, the index of indpendent ec is the key
                    The key can be int or float or str (starts with C or just numbers), such as 11, '11', '11.0', 'C11' 
        Ord: int
        CrystalType: str
    Return
    ------
        CIJ_full: list
            Full expression in Voigt's notation
    '''
    CrystalType = esutils.crystaltypemap(CrystalType)
    CoefInd = symdata.coef_ind(CrystalType=CrystalType, Ord=Ord)
    CoefCoef = symdata.coef_crystal(CrystalType=CrystalType, Ord=Ord)
    CoefUniq = symdata.get_unique(CoefInd)
    CIJ_index = [essym.num2cijk(CoefUniq_i, Ord) for CoefUniq_i in CoefUniq]
    indpenC_new = indpen2dict(indpenC, CIJ_index=CIJ_index)
    CIJ_full = []
    N = 6
    for i in range(N ** Ord):
        Cindex = essym.Num2IJK(i + 1, N, Ord)
        Cindex = -np.sort(-Cindex)
        #CIJnum is a list, here the len=1
        CIJnum = essym.cijk2num(sum([int(Cindexi) * 10 ** i for i, Cindexi in enumerate(Cindex)]), Ord)
        CIJIndpenNum = CoefInd[CIJnum[0]]
        CIJIndpenCoef = CoefCoef[CIJnum[0]]
        #print('{}-{}'.format(CIJIndpenNum, CIJIndpenCoef))
        if isinstance(CIJIndpenNum, list):
            if 0 in CIJIndpenNum:
                CijValue = 0
            else:
                CijValue = sum([float(CIJIndpenCoef[i])*float(indpenC_new[essym.num2cijk(Numi, Ord)]) for i, Numi in enumerate(CIJIndpenNum)])
        else:
            #It's already a independent
            if CIJIndpenNum == 0:
                CijValue = 0
            else:
                CijValue = float(CIJIndpenCoef)*float(indpenC_new[essym.num2cijk(CIJIndpenNum, Ord)])
        CIJ_full.append(CijValue)
    CIJ_full = np.array(CIJ_full).reshape([6]*Ord)        
    return CIJ_full

def full2indpen(CIJ_full, Ord=2, CrystalType='c1'):
    CrystalType = esutils.crystaltypemap(CrystalType)
    CoefInd = symdata.coef_ind(CrystalType=CrystalType, Ord=Ord)
    CoefUniq = symdata.get_unique(CoefInd)
    CIJ_index = [essym.num2cijk(CoefUniq_i, Ord) for CoefUniq_i in CoefUniq]
    CIJ_index = [[int(i) for i in str(item)] for item in CIJ_index]
    indepenC = []
    for indexi in CIJ_index:
        CIJ_full_tmp = copy.deepcopy(CIJ_full)
        for indi in indexi:
            CIJ_full_tmp = CIJ_full_tmp[indi-1]
        indepenC.append(CIJ_full_tmp)
    return indepenC

def full2tensor(CIJ_full):
    return NthOrderElasticTensor.from_voigt(CIJ_full)

def tensor2full(CIJ_tensor):
    return CIJ_tensor.voigt

def tensor_rotate(CIJ_tensor, rotate_M):
    return CIJ_tensor.rotate(rotate_M)

def independC_rotate(indpenC, rotate_M, Ord=2, CrystalType='c1', rotated_ct='n'):
    '''
    Independent cij rotation
    Parameter
    --------
        indpenC: list/dict
            Independent elastic constants
                If list, in the order of uniq. e.g. [1054, 119, 562] for c1 and Ord=2 means C11=1054, C12=119,C44=563 
                If dict, the index of indpendent ec is the key
                    The key can be int or float or str (starts with C or just numbers), such as 11, '11', '11.0', 'C11' 
        rotate_M: 3x3 list
            rotation matrix
        Ord: int
        CrystalType: str
            The crystal type
        rotated_ct: str
            The crystal type after rotation.
    Return
    ------
    '''
    cij_full = indpen2full(indpenC, Ord=Ord, CrystalType=CrystalType)
    cij_tensor = full2tensor(cij_full)
    cij_rotate = cij_tensor.rotate(rotate_M)
    cij_full_r = tensor2full(cij_rotate)
    indepenC_r = full2indpen(cij_full_r, Ord=Ord, CrystalType=rotated_ct)
    return indepenC_r



